Locale.Code = "en"

local changed = Instance.new("BindableEvent")
Locale.Changed = changed.Event

-- "id-id" -> "id", "pt-br" -> "pt", "zh-tw"/"zh-hk"/"zh-hant" -> "zh-tw", "zh-*" -> "zh-cn"
function Locale.Resolve(localeId: string?): string
	local normalized = string.gsub(localeId or "", "_", "-")
	local id = string.lower(normalized)
	if string.sub(id, 1, 2) == "zh" then
		if string.find(id, "tw", 1, true) or string.find(id, "hk", 1, true) or string.find(id, "hant", 1, true) then
			return "zh-tw"
		end
		return "zh-cn"
	end
	local short = string.sub(id, 1, 2)
	if Locale.Strings[short] then
		return short
	end
	return "en"
end

local function detect(): string
	if Locale.ForceLanguage and Locale.Strings[Locale.ForceLanguage] then
		return Locale.ForceLanguage
	end
	local player = Players.LocalPlayer
	local localeId = if player then player.LocaleId else ""
	if localeId == "" then
		localeId = LocalizationService.RobloxLocaleId
	end
	return Locale.Resolve(localeId)
end

function Locale.Set(code: string)
	if Locale.Strings[code] and code ~= Locale.Code then
		Locale.Code = code
		changed:Fire(code)
	end
end

local initialized = false
function Locale.Init()
	if initialized then
		return
	end
	initialized = true
	Locale.Code = detect()

	local player = Players.LocalPlayer
	if player then
		player:GetPropertyChangedSignal("LocaleId"):Connect(function()
			Locale.Set(detect())
		end)
	end
	LocalizationService:GetPropertyChangedSignal("RobloxLocaleId"):Connect(function()
		Locale.Set(detect())
	end)
end

function Locale.Get(key: string, ...: any): string
	local text = Locale.Strings[Locale.Code][key] or Locale.Strings.en[key] or key
	if select("#", ...) > 0 then
		local ok, result = pcall(string.format, text, ...)
		if ok then
			return result
		end
	end
	return text
end

return Locale
